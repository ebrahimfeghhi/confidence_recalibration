#!/bin/bash
# WAIT FOR CARDS 4, 5 AND 7 TO BE FREE, THEN LAUNCH THE DECAYING-LR ARM.
#
# Usage:  ./shell_scripts/queue_lrdecay_when_free.sh      (run it as a tracked background task,
#         NOT with a trailing & inside a compound command: $! there is the wrapper subshell rather
#         than this script, and on 2026-10-26 that made three "stopped the old chain" attempts
#         signal the wrong pid while both real chains kept running.)
#
# IT POLLS cards_busy.py, NOT PIDS. Earlier chains waited on an explicit rank pid list, which is
# correct when you know which run you are following; here the blocker is whatever happens to hold
# a card, so the question is "are the cards free" and cards_busy.py is the one sanctioned way to
# ask it. No grep, no /proc cmdline scan.
#
# NO KILL ANYWHERE IN HERE, and that is structural rather than careful: this script contains no
# kill, no pkill and no signal of any kind, so the worst it can do is fail to launch. A queue that
# can kill is a queue that can kill the wrong thing at 3am.
#
# DO NOT EDIT THIS FILE WHILE AN INSTANCE IS EXECUTING IT. bash reads a script lazily, so an edit
# shifts byte offsets under the running shell -- editing a chain mid-run on 2026-10-26 produced
# "line 31: /extra_training: No such file or directory" from a cd at line 26 and ended with two
# chains and six processes on three cards.
#
# THE LAUNCH SCRIPT REFUSES ON ITS OWN if the cards are busy, so there are two independent gates
# and neither path can land on an occupied card.
set -u
cd /home/ebrahim/confidence_recalibration/extra_training
PY_BIN=/home/ebrahim/Protenix/.venv/bin/python
echo $$ > training/runs/lrdecay_queue_pid
echo "$(TZ=America/New_York date '+%F %-I:%M %p %Z') queue armed for the decaying-lr arm"
echo "  waiting for cards 4,5,7; polling every 60s, 72h ceiling"
for i in $(seq 1 4320); do
  BUSY=$($PY_BIN -I run_logging/cards_busy.py 2>&1 | tail -1)
  if [ "$BUSY" = "0" ]; then
    echo "$(TZ=America/New_York date '+%F %-I:%M %p %Z') cards free after $((i - 1)) poll(s); launching"
    exec ./shell_scripts/launch_fullhead_l2sp_1e3_lrdecay.sh
  fi
  # Report hourly rather than every minute, so the log stays readable over a multi-day wait.
  [ $((i % 60)) -eq 1 ] && echo "  $(TZ=America/New_York date '+%-I:%M %p') still waiting (busy=$BUSY)"
  sleep 60
done
echo "$(TZ=America/New_York date '+%-I:%M %p') TIMEOUT after 72h; nothing launched"
exit 1
