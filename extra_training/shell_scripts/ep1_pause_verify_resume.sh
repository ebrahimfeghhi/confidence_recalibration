#!/bin/bash
# Pause ij24wr after epoch 1, run the ipTM join verification on free cards, then resume it.
#
#   nohup ./shell_scripts/ep1_pause_verify_resume.sh > training/runs/ep1_pause.log 2>&1 &
#
# WHY A PAUSE. The join verification's --compare checks PER-POSE ipTM against the eval's own rows,
# and that only means anything if nothing else is sharing a GPU: with inputs, head and weights
# identical, ipTM must agree to float precision, so ANY difference is the join. Tonight's earlier
# attempt ran beside a training arm and its output was discarded for exactly that reason.
#
# ONE SCRIPT, NO SECOND STAGE. Tonight's mess came from two instances of a chain surviving three
# "stops" -- $! in a compound command is the wrapper subshell, not the backgrounded script -- and
# then both acting. So this writes its OWN pid from inside, to training/runs/ep1_pause_pid, and
# nothing is queued after it. DO NOT EDIT THIS FILE WHILE IT RUNS: bash reads a script lazily and
# an edit underneath a live instance sends it to a wrong offset, which is the other half of what
# went wrong tonight.
set -u
cd /home/ebrahim/confidence_recalibration/extra_training
PY_BIN=/home/ebrahim/Protenix/.venv/bin/python
RID=ij24wr
HOLDERS="306042 306045 306050"
echo $$ > training/runs/ep1_pause_pid
say() { echo "$(TZ=America/New_York date '+%F %I:%M:%S %p %Z') $*"; }

say "armed; waiting for $RID epoch 1 (metric + checkpoint)"
for i in $(seq 1 480); do            # 4h ceiling at 30s
  [ -f "training/runs/$RID/metric_train_ep1.json" ] && \
    [ -f "training/runs/$RID/resume_ep1.pt" ] && break
  sleep 30
done
if [ ! -f "training/runs/$RID/metric_train_ep1.json" ] || [ ! -f "training/runs/$RID/resume_ep1.pt" ]; then
  say "TIMEOUT: $RID epoch 1 never completed. Doing nothing."; exit 1
fi
say "epoch 1 complete: $(grep -E '^  epoch 1 TRAIN:' training/runs/$RID/run.log | tail -1)"

# ---- stop the arm -------------------------------------------------------------------------
# THE PIDS COME FROM GPU OCCUPANCY, never from a /proc cmdline scan: the string such a scan looks
# for is present in the scanning command itself, which is how a check in this very session matched
# its own shell. cards_busy already excludes the three holders.
RANKS=$($PY_BIN -I run_logging/cards_busy.py 2>&1 | grep -oE "pid [0-9]+" | awk '{print $2}' | sort -un | tr '\n' ' ')
say "ranks on the cards: $RANKS"
[ -n "$RANKS" ] || { say "no ranks on the cards; refusing to guess what to stop"; exit 1; }
PARENTS=""
for P in $RANKS; do
  for H in $HOLDERS; do [ "$P" = "$H" ] && continue 2; done
  PP=$(awk '{print $4}' "/proc/$P/stat" 2>/dev/null) || continue
  case " $PARENTS " in *" $PP "*) ;; *) PARENTS="$PARENTS $PP";; esac
done
STOPPED=0
for PP in $PARENTS; do
  C=$(tr '\0' ' ' < "/proc/$PP/cmdline" 2>/dev/null)
  case "$C" in
    *torchrun*nproc_per_node*) kill "$PP" && { say "SIGTERM to torchrun $PP"; STOPPED=1; } ;;
    *) say "not torchrun, leaving alone: $PP" ;;
  esac
done
[ "$STOPPED" = "1" ] || { say "found no torchrun to stop; aborting rather than guessing"; exit 1; }

for i in $(seq 1 60); do
  BUSY=$($PY_BIN -I run_logging/cards_busy.py 2>&1 | tail -1)
  [ "$BUSY" = "0" ] && break
  sleep 10
done
BUSY=$($PY_BIN -I run_logging/cards_busy.py 2>&1 | tail -1)
[ "$BUSY" = "0" ] || { say "cards still busy ($BUSY) after 10 min; NOT running the verification, NOT resuming"; exit 1; }
say "cards free"
for H in $HOLDERS; do
  [ -d "/proc/$H" ] || say "FLAG: GPU holder $H is GONE"
done

# ---- the verification, bounded ------------------------------------------------------------
# Against dntxmn epoch 16, whose eval shards are complete and whose architecture derivation was
# checked by hand. Bounded so a wedged pass cannot keep the arm paused indefinitely.
say "running the ipTM join verification on dntxmn epoch 16"
timeout --signal=TERM --kill-after=120s 60m ./shell_scripts/verify_iptm_join.sh dntxmn 16
JOINRC=$?
case "$JOINRC" in
  0)   say "JOIN VERIFIED" ;;
  124|137) say "join verification TIMED OUT after 60 min -- treated as NOT verified" ;;
  *)   say "join NOT verified (exit $JOINRC) -- the separate DockQ eval stays" ;;
esac

# ---- resume ------------------------------------------------------------------------------
for i in $(seq 1 60); do
  BUSY=$($PY_BIN -I run_logging/cards_busy.py 2>&1 | tail -1)
  [ "$BUSY" = "0" ] && break
  sleep 10
done
BUSY=$($PY_BIN -I run_logging/cards_busy.py 2>&1 | tail -1)
[ "$BUSY" = "0" ] || { say "cards busy ($BUSY); NOT resuming. Resume by hand with shell_scripts/resume_ij24wr.sh"; exit 1; }
say "resuming $RID from epoch 1"
./shell_scripts/resume_ij24wr.sh
RC=$?
say "resume launcher returned $RC (join rc=$JOINRC)"
exit $RC
