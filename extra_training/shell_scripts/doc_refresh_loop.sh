#!/bin/bash
# Hourly: regenerate EXPERIMENTS.md's live block + the overlay figure, commit, push.
#
# Usage:  nohup ./shell_scripts/doc_refresh_loop.sh > training/runs/doc_refresh.log 2>&1 &
#
# WHY A SHELL LOOP AND NOT A CRON THAT WAKES THE SESSION. Nothing here needs a judgement call:
# experiments_doc.py discovers the arms, recomputes every number from the shards and rewrites one
# delimited block. Waking the model hourly to run one deterministic script would cost tokens to
# produce the same bytes.
#
# EXPLICIT FILE LIST, never `git add -A`. The run directories hold multi-GB checkpoints and a
# broad add could not be undone cheaply -- the same rule push_findings.sh follows.
#
# IT REFUSES rather than pushing something wrong: a detached HEAD, a failed regeneration, or a
# rejected push all leave the tree alone and are reported. A rejected push is NOT force-retried;
# the per-epoch watcher pushes to the same branch, so a rejection means it landed something first
# and the next tick will rebase onto it.
set -u
ROOT=/home/ebrahim/confidence_recalibration
cd "$ROOT/extra_training"
PY_BIN=/home/ebrahim/Protenix/.venv/bin/python
EVERY="${1:-3600}"

while :; do
  TS=$(TZ=America/New_York date '+%F %-I:%M %p %Z')
  BR=$(git -C "$ROOT" rev-parse --abbrev-ref HEAD)
  if [ "$BR" = "HEAD" ]; then
    echo "$TS REFUSED: detached HEAD"
  else
    OUT=$($PY_BIN -I run_logging/experiments_doc.py 2>&1)
    RC=$?
    if [ "$RC" != "0" ]; then
      echo "$TS regeneration FAILED rc=$RC: $OUT"
    else
      git -C "$ROOT" add -- \
        extra_training/EXPERIMENTS.md \
        extra_training/figures/arms_overlay.png \
        extra_training/run_logging/experiments_doc.py \
        extra_training/shell_scripts/doc_refresh_loop.sh
      if git -C "$ROOT" diff --cached --quiet; then
        echo "$TS $OUT; nothing to push"
      else
        git -C "$ROOT" commit -q -m "EXPERIMENTS.md: refresh live results ($TS)" \
          -m "Regenerated by run_logging/experiments_doc.py from each run's own train_eval shards and rank_rho cache." \
          -m "Co-Authored-By: Claude Opus 5 <noreply@anthropic.com>"
        # REBASE FIRST, because the per-epoch watcher pushes to this same branch.
        git -C "$ROOT" pull -q --rebase origin "$BR" 2>/dev/null
        if git -C "$ROOT" push -q origin "$BR"; then
          echo "$TS $OUT; pushed $(git -C "$ROOT" rev-parse --short HEAD)"
        else
          echo "$TS $OUT; PUSH REJECTED -- left committed locally, retrying next tick"
        fi
      fi
    fi
  fi
  sleep "$EVERY"
done
